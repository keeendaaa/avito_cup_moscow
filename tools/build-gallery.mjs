// Regenerates assets/listings/manifest.mjs from the collected photos.
// Each file is named "<listing-id>-<n>.jpg"; the ids match listings in model.mjs.
import { readdir, writeFile } from 'node:fs/promises';

const dir = new URL('../assets/listings/', import.meta.url);
const files = (await readdir(dir)).filter(name => /^[a-z]+-\d+\.jpg$/.test(name));
const gallery = {};
for (const name of files) {
  const [id] = name.split('-');
  (gallery[id] ||= []).push('listings/' + name.replace(/\.jpg$/, ''));
}
for (const id of Object.keys(gallery)) {
  gallery[id].sort((a, b) => Number(a.split('-').at(-1).slice(0, -4)) - Number(b.split('-').at(-1).slice(0, -4)));
}
const body = `// Generated by tools/build-gallery.mjs. Lists local photos per listing.\nexport const gallery = ${JSON.stringify(gallery, null, 2)};\n`;
await writeFile(new URL('manifest.mjs', dir), body);
console.log(`listings: ${Object.keys(gallery).length}, photos: ${files.length}`);
